"""
OSM Data Toolkit - Overpass Downloader
=====================================

This module handles downloading raw OSM data from the Overpass API.

Current Development Stage
--------------------------
Step 2.5 — OSM Data Acquisition
Progress reporting and cancellation support.

Responsibilities:
    1. Send an already-generated Overpass QL query to Overpass.
    2. Try multiple Overpass servers if necessary.
    3. Retry failed requests with exponential backoff.
    4. Validate the HTTP response.
    5. Parse and validate the returned JSON.
    6. Return the raw Overpass response to the caller.
    7. Provide a small response summary for logging.
    8. Report download progress through an optional callback.

Important Design Decision
-------------------------
The Overpass query itself is generated by ``core.overpass``.

This module does NOT:
    - define OSM feature tags;
    - construct Overpass QL;
    - process geometries;
    - create GeoPackages;
    - create Shapefiles;
    - add QGIS layers.

It is deliberately responsible only for communication with
the Overpass API.

The downloader uses the same general strategy as the user's
existing OSM workflow:

    Overpass server 1
        ↓
    retries
        ↓
    Overpass server 2
        ↓
    retries
        ↓
    Overpass server 3
        ↓
    final error

This makes the plugin considerably more resilient to a busy
or temporarily unavailable Overpass instance.

Progress reporting
------------------
The downloader can optionally report its current state through
a callback function.

The callback receives a simple string message.

For example:

    progress_callback("Trying Overpass server 1/3...")
    progress_callback("Attempt 2/3...")
    progress_callback("Retrying in 4 seconds...")

The downloader deliberately does not depend on Qt or QGIS.
The background worker can connect this callback to a Qt signal.
"""


# =============================================================================
# IMPORTS
# =============================================================================

import time

from typing import Any, Callable, Dict, List, Optional

import requests


# =============================================================================
# DEFAULT SETTINGS
# =============================================================================

# -------------------------------------------------------------------------
# Overpass servers
# -------------------------------------------------------------------------
#
# These are the servers used by the user's existing OSM workflow.
#
# The downloader tries them in this order. If one server fails after
# the configured retries, the next server is attempted.
# -------------------------------------------------------------------------

DEFAULT_OVERPASS_SERVERS = [
    "https://overpass-api.de/api/interpreter",
    "https://lz4.overpass-api.de/api/interpreter",
    "https://overpass.kumi.systems/api/interpreter",
]


# -------------------------------------------------------------------------
# Request settings
# -------------------------------------------------------------------------

DEFAULT_REQUEST_TIMEOUT = 300

DEFAULT_RETRIES_PER_SERVER = 3

DEFAULT_INITIAL_BACKOFF = 2.0

DEFAULT_BACKOFF_MULTIPLIER = 2.0


# -------------------------------------------------------------------------
# HTTP request headers
# -------------------------------------------------------------------------
#
# A descriptive User-Agent is useful when communicating with public
# services.
# -------------------------------------------------------------------------

DEFAULT_HEADERS = {
    "User-Agent": "OSM-Data-Toolkit-QGIS/1.0",
    "Accept": "application/json",
}


# =============================================================================
# TYPE ALIASES
# =============================================================================

# -------------------------------------------------------------------------
# Optional callback used to report progress to the caller.
#
# The downloader only sends text messages. It does not know whether the
# caller is QGIS, a command-line script, a notebook, or something else.
# -------------------------------------------------------------------------

ProgressCallback = Callable[[str], None]
CancelCheck = Callable[[], bool]


# =============================================================================
# CUSTOM EXCEPTION
# =============================================================================

class OverpassDownloadError(RuntimeError):
    """
    Raised when the Overpass downloader cannot obtain valid data.

    The exception is intentionally separate from requests exceptions
    so the GUI/controller can handle all downloader failures using
    one predictable exception type.
    """

    pass


class OverpassDownloadCancelled(RuntimeError):
    """
    Raised when the caller requests cancellation of an Overpass download.

    This exception is deliberately distinct from download failures so the
    background worker can emit its ``cancelled`` signal instead of ``error``.
    """

    pass


# =============================================================================
# INTERNAL HELPERS
# =============================================================================

def _validate_download_parameters(
    query: str,
    overpass_servers: List[str],
    request_timeout: int,
    retries_per_server: int,
    initial_backoff: float,
    backoff_multiplier: float,
) -> None:
    """
    Validate downloader configuration before making network requests.

    Raises
    ------
    ValueError
        If any required parameter is invalid.
    """

    if not isinstance(query, str) or not query.strip():
        raise ValueError(
            "Overpass query must be a non-empty string."
        )

    if not overpass_servers:
        raise ValueError(
            "At least one Overpass server must be provided."
        )

    for server in overpass_servers:

        if not isinstance(server, str) or not server.strip():
            raise ValueError(
                "All Overpass server URLs must be non-empty strings."
            )

    if request_timeout <= 0:
        raise ValueError(
            "request_timeout must be greater than zero."
        )

    if retries_per_server <= 0:
        raise ValueError(
            "retries_per_server must be greater than zero."
        )

    if initial_backoff < 0:
        raise ValueError(
            "initial_backoff cannot be negative."
        )

    if backoff_multiplier < 1:
        raise ValueError(
            "backoff_multiplier must be at least 1."
        )


# =============================================================================
# SINGLE REQUEST
# =============================================================================

def _request_overpass_server(
    query: str,
    server_url: str,
    request_timeout: int,
) -> Dict[str, Any]:
    """
    Send one Overpass request to one server.

    Parameters
    ----------
    query:
        Complete Overpass QL query.

    server_url:
        Overpass API interpreter URL.

    request_timeout:
        Maximum number of seconds to wait for the HTTP request.

    Returns
    -------
    dict
        Parsed Overpass JSON response.

    Raises
    ------
    requests.exceptions.RequestException
        For HTTP/network/request failures.

    ValueError
        If the server returns invalid JSON or an unexpected structure.
    """

    # ---------------------------------------------------------------------
    # Send the query as form data.
    # ---------------------------------------------------------------------

    response = requests.post(
        server_url,
        data={"data": query},
        headers=DEFAULT_HEADERS,
        timeout=request_timeout,
    )

    # ---------------------------------------------------------------------
    # Raise an exception for HTTP errors such as:
    #
    # 429 - Too Many Requests
    # 500 - Server Error
    # 502 - Bad Gateway
    # 503 - Service Unavailable
    # 504 - Gateway Timeout
    # ---------------------------------------------------------------------

    response.raise_for_status()

    # ---------------------------------------------------------------------
    # Parse JSON.
    # ---------------------------------------------------------------------

    try:

        response_data = response.json()

    except ValueError as exc:

        # Keep a small part of the response for diagnostics without
        # dumping a potentially huge server response into the log.

        preview = response.text[:500].strip()

        raise ValueError(
            "Overpass server returned invalid JSON. "
            f"Response preview: {preview}"
        ) from exc

    # ---------------------------------------------------------------------
    # Validate the basic Overpass response structure.
    # ---------------------------------------------------------------------

    if not isinstance(response_data, dict):

        raise ValueError(
            "Overpass response is not a JSON object."
        )

    if "elements" not in response_data:

        raise ValueError(
            "Overpass response does not contain an 'elements' field."
        )

    if not isinstance(response_data["elements"], list):

        raise ValueError(
            "Overpass response 'elements' field is not a list."
        )

    return response_data


# =============================================================================
# CANCELLATION HELPERS
# =============================================================================

def _raise_if_cancelled(cancel_check: Optional[CancelCheck]) -> None:
    """Raise a dedicated exception when the caller requests cancellation."""

    if cancel_check is not None and cancel_check():
        raise OverpassDownloadCancelled(
            "Overpass download was cancelled by the caller."
        )


def _wait_with_cancellation(
    delay_seconds: float,
    cancel_check: Optional[CancelCheck],
    *,
    check_interval: float = 0.2,
) -> None:
    """Wait for a retry delay in short intervals so cancellation is responsive."""

    remaining = max(0.0, float(delay_seconds))

    while remaining > 0:
        _raise_if_cancelled(cancel_check)

        sleep_for = min(check_interval, remaining)
        time.sleep(sleep_for)
        remaining -= sleep_for

    _raise_if_cancelled(cancel_check)


# =============================================================================
# MAIN DOWNLOADER
# =============================================================================

def download_overpass_data(
    query: str,
    *,
    overpass_servers: Optional[List[str]] = None,
    request_timeout: int = DEFAULT_REQUEST_TIMEOUT,
    retries_per_server: int = DEFAULT_RETRIES_PER_SERVER,
    initial_backoff: float = DEFAULT_INITIAL_BACKOFF,
    backoff_multiplier: float = DEFAULT_BACKOFF_MULTIPLIER,
    progress_callback: Optional[ProgressCallback] = None,
    cancel_check: Optional[CancelCheck] = None,
) -> Dict[str, Any]:
    """
    Download raw OSM data from Overpass using multiple servers.

    Parameters
    ----------
    query:
        Complete Overpass QL query generated by ``core.overpass``.

    overpass_servers:
        Optional list of Overpass API interpreter URLs.

        If omitted, the three default servers are used.

    request_timeout:
        Maximum HTTP request duration in seconds.

    retries_per_server:
        Number of attempts made against each server.

    initial_backoff:
        Number of seconds before the first retry.

    backoff_multiplier:
        Multiplier applied to the backoff delay after each failure.

    progress_callback:
        Optional callback function used to report progress.

        The callback must accept one string argument.

        Example:

            progress_callback("Trying Overpass server 1/3...")

        If no callback is supplied, progress reporting is simply
        skipped.

    cancel_check:
        Optional zero-argument callback that returns True when cancellation
        has been requested. It is checked before server attempts, after each
        HTTP request, and during retry backoff delays. An active blocking HTTP
        request cannot be forcibly interrupted; cancellation is checked as
        soon as that request returns or raises an exception.

    Returns
    -------
    dict
        Raw parsed Overpass JSON response.

    Raises
    ------
    OverpassDownloadError
        If all servers and retries fail.

    OverpassDownloadCancelled
        If cancellation is requested through ``cancel_check``.

    ValueError
        If the supplied configuration is invalid.

    Notes
    -----
    The function deliberately returns the complete raw response.

    Later processing modules can therefore:
        - convert it to GeoDataFrames;
        - save it as raw JSON;
        - cache it;
        - generate output layers.

    No data is discarded at this stage.
    """

    # ---------------------------------------------------------------------
    # Use default servers when the caller does not provide a custom list.
    # ---------------------------------------------------------------------

    servers = (
        list(overpass_servers)
        if overpass_servers is not None
        else list(DEFAULT_OVERPASS_SERVERS)
    )

    # ---------------------------------------------------------------------
    # Validate all parameters before starting network activity.
    # ---------------------------------------------------------------------

    _validate_download_parameters(
        query=query,
        overpass_servers=servers,
        request_timeout=request_timeout,
        retries_per_server=retries_per_server,
        initial_backoff=initial_backoff,
        backoff_multiplier=backoff_multiplier,
    )

    # ---------------------------------------------------------------------
    # Respect cancellation before reporting or starting network activity.
    _raise_if_cancelled(cancel_check)

    # Keep a record of every failed attempt.
    #
    # This allows the final exception to explain exactly what happened
    # rather than reporting only the last failure.
    # ---------------------------------------------------------------------

    errors: List[str] = []

    # ---------------------------------------------------------------------
    # Report the overall download configuration.
    # ---------------------------------------------------------------------

    if progress_callback is not None:

        progress_callback(
            "Starting Overpass download..."
        )

        progress_callback(
            f"Overpass servers available: {len(servers)}"
        )

    # ---------------------------------------------------------------------
    # Try each Overpass server.
    # ---------------------------------------------------------------------

    for server_index, server_url in enumerate(servers, start=1):

        _raise_if_cancelled(cancel_check)

        # -------------------------------------------------------------
        # Report which server is being attempted.
        # -------------------------------------------------------------

        if progress_callback is not None:

            progress_callback(
                f"Trying Overpass server "
                f"{server_index}/{len(servers)}..."
            )

        # -------------------------------------------------------------
        # Try the current server multiple times.
        # -------------------------------------------------------------

        for attempt in range(1, retries_per_server + 1):

            _raise_if_cancelled(cancel_check)

            # ---------------------------------------------------------
            # Report the current attempt.
            # ---------------------------------------------------------

            if progress_callback is not None:

                progress_callback(
                    f"Server {server_index}/{len(servers)} — "
                    f"attempt {attempt}/{retries_per_server}..."
                )

            try:

                response_data = _request_overpass_server(
                    query=query,
                    server_url=server_url,
                    request_timeout=request_timeout,
                )

                # A request may have been running when cancellation was
                # requested. Check immediately after it returns.
                _raise_if_cancelled(cancel_check)

                # -----------------------------------------------------
                # Successful request.
                # -----------------------------------------------------

                if progress_callback is not None:

                    progress_callback(
                        f"Overpass server "
                        f"{server_index}/{len(servers)} responded "
                        "successfully."
                    )

                return response_data

            except requests.exceptions.Timeout as exc:

                message = (
                    f"Server {server_index}/{len(servers)}, "
                    f"attempt {attempt}/{retries_per_server}: "
                    f"timeout — {server_url} — {exc}"
                )

                errors.append(message)

                if progress_callback is not None:

                    progress_callback(
                        f"Timeout on server "
                        f"{server_index}/{len(servers)}."
                    )

            except requests.exceptions.ConnectionError as exc:

                message = (
                    f"Server {server_index}/{len(servers)}, "
                    f"attempt {attempt}/{retries_per_server}: "
                    f"connection error — {server_url} — {exc}"
                )

                errors.append(message)

                if progress_callback is not None:

                    progress_callback(
                        f"Connection error on server "
                        f"{server_index}/{len(servers)}."
                    )

            except requests.exceptions.HTTPError as exc:

                # -----------------------------------------------------
                # HTTP errors are recorded separately because they are
                # particularly useful for diagnosing Overpass problems.
                # -----------------------------------------------------

                response = getattr(exc, "response", None)

                if response is not None:

                    response_preview = (
                        response.text[:500].strip()
                    )

                    message = (
                        f"Server {server_index}/{len(servers)}, "
                        f"attempt {attempt}/{retries_per_server}: "
                        f"HTTP {response.status_code} — "
                        f"{server_url} — "
                        f"{response_preview}"
                    )

                    if progress_callback is not None:

                        progress_callback(
                            f"HTTP {response.status_code} error "
                            f"on server "
                            f"{server_index}/{len(servers)}."
                        )

                else:

                    message = (
                        f"Server {server_index}/{len(servers)}, "
                        f"attempt {attempt}/{retries_per_server}: "
                        f"HTTP error — {server_url} — {exc}"
                    )

                    if progress_callback is not None:

                        progress_callback(
                            f"HTTP error on server "
                            f"{server_index}/{len(servers)}."
                        )

                errors.append(message)

            except requests.exceptions.RequestException as exc:

                message = (
                    f"Server {server_index}/{len(servers)}, "
                    f"attempt {attempt}/{retries_per_server}: "
                    f"request error — {server_url} — {exc}"
                )

                errors.append(message)

                if progress_callback is not None:

                    progress_callback(
                        f"Request error on server "
                        f"{server_index}/{len(servers)}."
                    )

            except ValueError as exc:

                # -----------------------------------------------------
                # Invalid JSON or unexpected response structure.
                #
                # Treat this as a failed server attempt so another
                # Overpass server can be tried.
                # -----------------------------------------------------

                message = (
                    f"Server {server_index}/{len(servers)}, "
                    f"attempt {attempt}/{retries_per_server}: "
                    f"invalid response — {server_url} — {exc}"
                )

                errors.append(message)

                if progress_callback is not None:

                    progress_callback(
                        f"Invalid response from server "
                        f"{server_index}/{len(servers)}."
                    )

            # If cancellation was requested while the HTTP operation was
            # running, stop here rather than retrying or changing servers.
            _raise_if_cancelled(cancel_check)

            # ---------------------------------------------------------
            # If this was not the final attempt for this server,
            # wait before retrying.
            # ---------------------------------------------------------

            if attempt < retries_per_server:

                delay = (
                    initial_backoff
                    * (
                        backoff_multiplier
                        ** (attempt - 1)
                    )
                )

                if progress_callback is not None:

                    progress_callback(
                        f"Retrying in {delay:g} seconds..."
                    )

                _wait_with_cancellation(
                    delay,
                    cancel_check,
                )

        # -----------------------------------------------------------------
        # Current server has failed all retries.
        #
        # The loop now moves to the next Overpass server.
        # -----------------------------------------------------------------

        if progress_callback is not None:

            progress_callback(
                f"All attempts failed for server "
                f"{server_index}/{len(servers)}."
            )

    # =============================================================================
    # ALL SERVERS FAILED
    # =============================================================================

    _raise_if_cancelled(cancel_check)

    error_details = "\n".join(
        f"  - {error}"
        for error in errors
    )

    if progress_callback is not None:

        progress_callback(
            "All Overpass servers and retry attempts failed."
        )

    raise OverpassDownloadError(
        "All Overpass servers and retry attempts failed.\n\n"
        f"Attempt details:\n{error_details}"
    )


# =============================================================================
# RESPONSE SUMMARY
# =============================================================================

def summarize_overpass_response(
    response_data: Dict[str, Any],
) -> Dict[str, int]:
    """
    Create a simple summary of an Overpass response.

    Parameters
    ----------
    response_data:
        Parsed raw Overpass JSON response.

    Returns
    -------
    dict
        Counts for total elements, nodes, ways and relations.
    """

    # ---------------------------------------------------------------------
    # Validate the basic structure.
    # ---------------------------------------------------------------------

    if not isinstance(response_data, dict):

        raise ValueError(
            "response_data must be a dictionary."
        )

    elements = response_data.get("elements", [])

    if not isinstance(elements, list):

        raise ValueError(
            "response_data['elements'] must be a list."
        )

    # ---------------------------------------------------------------------
    # Count element types.
    # ---------------------------------------------------------------------

    nodes = sum(
        1
        for element in elements
        if element.get("type") == "node"
    )

    ways = sum(
        1
        for element in elements
        if element.get("type") == "way"
    )

    relations = sum(
        1
        for element in elements
        if element.get("type") == "relation"
    )

    return {
        "total_elements": len(elements),
        "nodes": nodes,
        "ways": ways,
        "relations": relations,
    }


